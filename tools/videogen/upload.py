"""Generate supabase/seed.sql from out/exercises.json and (optionally) upload media to Storage.

    tools/videogen/.venv/bin/python -I tools/videogen/upload.py            # only write seed.sql
    SUPABASE_URL=... SUPABASE_SERVICE_ROLE_KEY=... \
    tools/videogen/.venv/bin/python -I tools/videogen/upload.py --upload   # + upload videos/thumbs

The service-role key bypasses RLS: keep it in your shell only, never in the repo or the APK.
"""
from __future__ import annotations

import json
import os
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
SEED = HERE.parent.parent / "supabase" / "seed.sql"
BUCKET = "exercise-media"


def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def sql_opt(s) -> str:
    return "null" if s is None else sql_str(s)


def sql_array(items) -> str:
    return "array[" + ", ".join(sql_str(i) for i in items) + "]::text[]"


def write_seed(catalog):
    rows = []
    for e in catalog:
        rows.append(
            f"  ({sql_str(e['slug'])}, {sql_str(e['name'])}, {sql_str(e['description'])}, {sql_array(e['muscle_groups'])}, "
            f"{sql_array(e['equipment'])}, {sql_str(e['type'])}, {e['difficulty']}, {str(e['unilateral']).lower()}, "
            f"{sql_opt(e.get('pregnancy'))}, {sql_str(e['video_path'])}, {sql_str(e['thumb_path'])})"
        )
    SEED.parent.mkdir(parents=True, exist_ok=True)
    SEED.write_text(
        "-- Generated by tools/videogen/upload.py from tools/videogen/out/exercises.json. Do not edit by hand.\n"
        "insert into public.exercises (slug, name, description, muscle_groups, equipment, type, difficulty, unilateral, pregnancy, video_path, thumb_path) values\n"
        + ",\n".join(rows)
        + "\non conflict (slug) do update set name = excluded.name, description = excluded.description,\n"
        "  muscle_groups = excluded.muscle_groups, equipment = excluded.equipment, type = excluded.type,\n"
        "  difficulty = excluded.difficulty, unilateral = excluded.unilateral, pregnancy = excluded.pregnancy,\n"
        "  video_path = excluded.video_path, thumb_path = excluded.thumb_path;\n",
        encoding="utf-8",
    )
    print(f"seed: {SEED} ({len(rows)} ejercicios)")


def upload(path: Path, remote: str, content_type: str):
    url = os.environ["SUPABASE_URL"].rstrip("/") + f"/storage/v1/object/{BUCKET}/{remote}"
    key = os.environ["SUPABASE_SERVICE_ROLE_KEY"]
    req = urllib.request.Request(url, data=path.read_bytes(), method="POST", headers={
        "Authorization": f"Bearer {key}", "apikey": key, "Content-Type": content_type, "x-upsert": "true",
        "Cache-Control": "max-age=31536000",
    })
    with urllib.request.urlopen(req) as resp:
        resp.read()


def main(argv):
    catalog = json.loads((OUT / "exercises.json").read_text(encoding="utf-8"))
    write_seed(catalog)
    if "--upload" in argv:
        for e in catalog:
            upload(OUT / e["video_path"], e["video_path"], "video/mp4")
            upload(OUT / e["thumb_path"], e["thumb_path"], "image/webp")
            print("subido", e["slug"])


if __name__ == "__main__":
    main(sys.argv[1:])
