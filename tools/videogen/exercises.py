from __future__ import annotations

import math

LEG = 158  # thigh + shin
BODY = 263  # ankle -> shoulder when the body is a straight line


def line_pose(ankle, theta, extra=None):
    """Straight body (plank / push-up) from `ankle`, `theta` degrees above horizontal, head towards +x."""
    c, s = math.cos(math.radians(theta)), math.sin(math.radians(theta))
    hip = (ankle[0] + LEG * c, ankle[1] + LEG * s)
    p = dict(hip=hip, torso=90 - theta, ln=("ik", *ankle), lf=("ik", ankle[0] - 4, ankle[1]), fn=10, ff=10)
    p.update(extra or {})
    return p


def knee_line_pose(knee, theta, extra=None):
    c, s = math.cos(math.radians(theta)), math.sin(math.radians(theta))
    hip = (knee[0] + 80 * c, knee[1] + 80 * s)
    thigh = math.degrees(math.atan2(-c, s))
    p = dict(hip=hip, torso=90 - theta, ln=("fk", thigh, -125), lf=("fk", thigh, -128), fn=-170, ff=-170)
    p.update(extra or {})
    return p


